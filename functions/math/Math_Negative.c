// Function: Math_Negative
// Get the negative (additive inverse) of a 8-bit register
//
// Parameters:
//   val - Signed 8-bit value to negate
//
// Return:
//   Negative value of the input
inline i8 Math_Negative(i8 val) { return -val; }
